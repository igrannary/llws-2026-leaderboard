/* LLWS 2026 Office Pool leaderboard.
   Reads data.json (regenerated by pool/update.py). No dependencies, no build.

   URL options:  ?view=standings|teams   pin a single view
                 ?rotate=20              seconds per view (default 14)
                 ?safe=4                 overscan inset, percent
                 ?rows=8                 force rows per standings page
                 ?debug=1                overlay what this screen reports
   Keyboard:     Space pauses rotation, Left/Right switch views,
                 [ and ] fit the picture to the TV, 0 resets.

   COMPATIBILITY: the office TV is driven by a BrightSign player, whose
   firmware carries an older Chromium than a desktop browser. Nothing here
   uses optional chaining, nullish coalescing or flexbox gap - all of which
   are Chromium 80/84 features, and the first two of which would fail to
   parse and take the whole page down rather than degrade. Keep it that way. */

const params = new URLSearchParams(location.search);
const ROTATE_OVERRIDE = parseFloat(params.get('rotate'));
const REFRESH_MS = 60000;
const PINNED = params.get('view');
const ROWS_OVERRIDE = parseInt(params.get('rows'), 10) || 0;
const DEBUG = params.get('debug') === '1';

/* ------------------------------------------------------- surviving a reload
   A signage player reloads the page on its own schedule, and BrightAuthor's
   default is often shorter than one full rotation. Starting from view 0
   every time means the later screens are never reached: the room sees page
   one of the standings and nothing else, no matter how long the TV is on.

   So the last screen shown is remembered, and a fresh load picks up at the
   NEXT one. However often the player reloads, the whole rotation still gets
   seen. */
/* ------------------------------------------------------ running stale code
   A signage player can hold on to a cached app.js long after a deploy, which
   shows the room fresh scores rendered by old code - data.json is fetched
   with a unique ?t= every time, the script is not. The script can tell: it
   reads the version off its own tag and compares it with the version in
   data.json, which is always current. On a mismatch it reloads once through
   a URL the player has never seen, which pulls a fresh index.html and with it
   fresh script and stylesheet URLs.

   The guard is the URL itself rather than storage, so there is no way to get
   into a reload loop on a player where storage does not persist. */
const MY_BUILD = (function () {
  const tags = document.getElementsByTagName('script');
  for (let i = 0; i < tags.length; i++) {
    const m = /app\.js\?v=([A-Za-z0-9]+)/.exec(tags[i].src || '');
    if (m) return m[1];
  }
  return '';
})();

function reloadIfStale(data) {
  if (!data.build || !MY_BUILD || data.build === MY_BUILD) return false;
  if (params.get('cb') === data.build) return false;   // already tried this one
  const next = new URLSearchParams(location.search);
  next.set('cb', data.build);
  location.replace(location.pathname + '?' + next.toString());
  return true;
}

const VIEW_KEY = 'llws-view-index';
let resumeFrom = 0;
try {
  const stored = parseInt(localStorage.getItem(VIEW_KEY), 10);
  if (!isNaN(stored)) resumeFrom = stored + 1;
} catch (e) { /* storage disabled on this player; start at the top */ }
let seeded = false;

/* ----------------------------------------------------------------- overscan
   Televisions crop the edges of an HDMI signal, typically 2-5% a side, which
   is what made the score column disappear off the side of the office TV.
   Everything is inset by a safe area the operator can tune on the screen
   itself: [ and ] nudge it, 0 resets, and the value is remembered per screen
   so it survives a reload. ?safe=4 sets it directly where there is no
   keyboard. */
const SAFE_KEY = 'llws-safe-percent';
const clampSafe = v => Math.min(12, Math.max(0, v));

function readSafe() {
  const fromUrl = parseFloat(params.get('safe'));
  if (!Number.isNaN(fromUrl)) return clampSafe(fromUrl);
  let stored = NaN;
  try { stored = parseFloat(localStorage.getItem(SAFE_KEY)); } catch (e) {}
  return Number.isNaN(stored) ? 3 : clampSafe(stored);
}

let safePercent = readSafe();
let safeHudTimer = null;

function applySafe(show) {
  const root = document.documentElement;
  root.style.setProperty('--safe-x', safePercent + 'vw');
  // Vertical crop is usually a little less aggressive than horizontal.
  root.style.setProperty('--safe-y', (safePercent * 0.8) + 'vh');
  if (!show) return;
  const hud = $('#safe-hud'), stage = $('#stage');
  if (!hud) return;
  hud.innerHTML = 'Screen fit &nbsp;' + safePercent.toFixed(1) + '%' +
    '<small>[ and ] to adjust &middot; 0 to reset</small>';
  hud.classList.add('on');
  stage.classList.add('calibrating');
  clearTimeout(safeHudTimer);
  safeHudTimer = setTimeout(() => {
    hud.classList.remove('on');
    stage.classList.remove('calibrating');
  }, 2600);
}

function nudgeSafe(delta) {
  safePercent = clampSafe(Math.round((safePercent + delta) * 10) / 10);
  try { localStorage.setItem(SAFE_KEY, safePercent); } catch (e) {}
  applySafe(true);
  if (currentData) { rebuildViews(currentData); renderStandings(currentData); }
}

/* Dwell per view: big pools paginate into more views, so shorten each one to
   keep a full cycle around a minute rather than a minute and a half. */
function rotateMs() {
  if (ROTATE_OVERRIDE) return ROTATE_OVERRIDE * 1000;
  const per = Math.min(14, Math.max(8, 75 / Math.max(1, VIEWS.length)));
  return per * 1000;
}

/* Views are built at render time: the standings paginate so rows stay large
   enough to read across a room no matter how many people enter. */
let VIEWS = [{ kind: 'standings', page: 0 }, { kind: 'teams' }];
let viewIndex = 0;
let paused = !!PINNED;
let rotateTimer = null;
let lastTotals = new Map();
let pageSize = 12;

/* Must match the compact-layout media query in style.css. */
const isNarrow = () =>
  window.matchMedia('(max-aspect-ratio: 5/4), (max-height: 620px)').matches;

