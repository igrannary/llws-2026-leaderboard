const $ = sel => document.querySelector(sel);
const el = (tag, cls, text) => {
  const n = document.createElement(tag);
  if (cls) n.className = cls;
  if (text !== undefined) n.textContent = text;
  return n;
};

/* ---------------------------------------------------------------- fetch */
async function load() {
  // The standalone preview (site/build_preview.py) embeds a snapshot instead
  // of serving data.json, so it can be opened or shared as a single file.
  if (window.__LLWS_DATA__) { render(window.__LLWS_DATA__); return; }
  try {
    const res = await fetch('data.json?t=' + Date.now(), { cache: 'no-store' });
    if (!res.ok) throw new Error(res.status);
    const data = await res.json();
    render(data);
  } catch (err) {
    $('#tick-latest').innerHTML =
      '<span class="dim">Waiting for the next update&hellip;</span>';
  }
}

/* ------------------------------------------------------------- rendering */
function render(data) {
  if (reloadIfStale(data)) return;
  currentData = data;
  renderHeader(data);
  rebuildViews(data);
  renderStandings(data);
  renderTeams(data);
  renderTicker(data);
  fitStandings(data);
  renderDebug(data);
}

/* Rebuild the view list around the current pageSize, keeping the screen the
   operator is looking at. */
function repaginate(data) {
  const pages = Math.max(1, Math.ceil(data.standings.length / pageSize));
  const current = VIEWS[viewIndex];
  VIEWS = [];
  for (let p = 0; p < pages; p++) VIEWS.push({ kind: 'standings', page: p });
  VIEWS.push({ kind: 'teams' });
  viewIndex = Math.min(viewIndex, VIEWS.length - 1);
  if (current && current.kind === 'teams') viewIndex = VIEWS.length - 1;
  showView(viewIndex);
  renderStandings(data);
}

/* Nothing may hide behind the ticker on a TV.

   This measures what the browser actually did rather than trusting the
   estimate, because an unfamiliar player can lay out differently: it reads
   the real distance between two rows and works out how many genuinely fit.
   The old version stepped down one row at a time and gave up after four,
   which on a screen that needed six steps left rows stranded off the bottom
   with no way to reach them. */
function fitStandings(data, guard = 0) {
  if (isNarrow() || guard > 12) return;
  const rows = [].slice.call(document.querySelectorAll('#standings .row'));
  if (rows.length < 2) return;
  const limit = $('#ticker').getBoundingClientRect().top;
  const first = rows[0].getBoundingClientRect();
  const last = rows[rows.length - 1].getBoundingClientRect();
  if (last.bottom <= limit + 1) return;

  const pitch = rows[1].getBoundingClientRect().top - first.top;
  const canFit = pitch > 0
    ? Math.max(1, Math.floor((limit - first.top) / pitch))
    : pageSize - 1;
  const next = Math.max(1, Math.min(canFit, pageSize - 1));
  if (next === pageSize) return;
  pageSize = next;
  repaginate(data);
  fitStandings(data, guard + 1);
}

/* How many rows fit above the ticker at this viewport, and what pages follow. */
function rowsThatFit(n) {
  const avail = $('#ticker').getBoundingClientRect().top
                - $('#standings').getBoundingClientRect().top - 4;
  const vh = window.innerHeight / 100;
  // Nominal row height from CSS, never a measured one: rows stretch to fill
  // the column, so measuring them here would feed their own stretch back into
  // the count and oscillate.
  const declared = getComputedStyle(document.documentElement)
                     .getPropertyValue('--row-h').trim();
  const preferredH = ((parseFloat(declared) || 7.5) + 0.62) * vh;
  // .row min-height + margin: the most that can be crammed in before rows
  // start disappearing behind the ticker.
  const floorH = (5.6 + 0.62) * vh;
  const hardMax = Math.max(1, Math.floor(avail / floorH));
  const preferred = Math.max(1, Math.floor(avail / preferredH));
  return Math.max(1, Math.min(preferred, hardMax, Math.max(n, 1)));
}

function rebuildViews(data) {
  const n = data.standings.length;
  if (isNarrow()) {
    pageSize = n || 1;
  } else {
    pageSize = ROWS_OVERRIDE || rowsThatFit(n);
  }
  const pages = Math.max(1, Math.ceil((n || 1) / pageSize));
  const next = [];
  for (let p = 0; p < pages; p++) next.push({ kind: 'standings', page: p });
  next.push({ kind: 'teams' });

  const current = VIEWS[viewIndex];
  VIEWS = next;
  if (PINNED === 'teams') viewIndex = VIEWS.length - 1;
  else if (PINNED === 'standings') viewIndex = 0;
  else if (!seeded) {
    // First paint after a load: carry on from wherever the last load stopped.
    viewIndex = ((resumeFrom % VIEWS.length) + VIEWS.length) % VIEWS.length;
    seeded = true;
  } else {
    const same = VIEWS.findIndex(v => current && v.kind === current.kind &&
                                      v.page === current.page);
    viewIndex = same >= 0 ? same : 0;
  }
  showView(viewIndex);
  restartRotation();
}

function renderHeader(data) {
  const phase = $('#phase');
  phase.classList.toggle('champ', !!data.champion);
  if (data.champion) {
    phase.textContent =
      (data.champion_display || shown(data.champion)) + ' — World Champion';
  } else if (data.us_champion || data.intl_champion) {
    phase.textContent = 'Championship Sunday';
  } else if (data.games_played === 0) {
    phase.textContent = 'First pitch Aug 19';
  } else {
    const next = data.upcoming.find(g => g.ready) || data.upcoming[0];
    phase.textContent = next ? next.label : 'In progress';
  }
  $('#progress').textContent =
    `Game ${data.games_played} of ${data.games_total}`;
  /* "Updated" reads as "we last looked", so it has to mean that. The
     updater republishes at least every half hour even when nothing has
     happened, so a stale time here is a real fault rather than a quiet
     afternoon. */
  $('#updated').textContent = 'Checked ' + (data.generated_display || '');
}

function pickClass(p) {
  if (p.state === 'world_champion' || p.state === 'side_champion') return 'crown';
  if (!p.alive) return 'out';
  return p.state === 'elimination' ? 'elimination' : 'winners';
}

function renderStandings(data) {
  const list = $('#standings');
  const view = VIEWS[viewIndex] || { kind: 'standings', page: 0 };
  const page = view.kind === 'standings' ? view.page : 0;
  const rows = data.standings.slice(page * pageSize, (page + 1) * pageSize);

  const pages = VIEWS.filter(v => v.kind === 'standings').length;
  $('#page-note').textContent =
    pages > 1 ? `Standings ${page + 1} of ${pages}` : '';

  if (!data.standings.length) {
    list.innerHTML = '';
    const empty = el('li', 'row');
    empty.append(el('div', 'name', 'Entries load after the Aug 18 deadline'));
    list.append(empty);
    return;
  }

  /* FLIP: measure current positions so reordering animates. */
  const before = new Map();
  list.querySelectorAll('.row').forEach(r =>
    before.set(r.dataset.name, r.getBoundingClientRect().top));

  list.innerHTML = '';
  rows.forEach(r => {
    const row = el('li', 'row');
    row.dataset.name = r.name;
    if (r.rank <= 3) row.classList.add('top' + r.rank);

    const rankCell = el('div', 'rank-cell');
    rankCell.append(el('span', 'rank-num', r.rank));
    let mv = '–', mvClass = 'flat';
    if (r.movement > 0) { mv = '▲' + r.movement; mvClass = 'up'; }
    else if (r.movement < 0) { mv = '▼' + Math.abs(r.movement); mvClass = 'down'; }
    rankCell.append(el('span', 'move ' + mvClass, mv));
    row.append(rankCell);

    row.append(el('div', 'name', r.name));

    const picks = el('div', 'picks');
    r.picks.forEach(p => {
      const chip = el('div', 'pick ' + pickClass(p) + (p.rank === 1 ? ' r1' : ''));
      chip.title = `#${p.rank} ${p.display || shown(p.team)} (${p.team}) — ` +
                   `${p.points} pts × rank weight = ${p.contribution}`;
      chip.append(el('span', 'abbr', p.abbr || abbr(p.team)));
      picks.append(chip);
    });
    row.append(picks);

    const alive = el('div', 'alive');
    alive.append(document.createTextNode(r.alive));
    alive.append(el('span', 'of', '/8'));
    row.append(alive);

    const score = el('div', 'score');
    row.append(score);
    countUp(score, lastTotals.has(r.name) ? lastTotals.get(r.name) : r.total,
            r.total);
    if (lastTotals.has(r.name) && lastTotals.get(r.name) !== r.total) {
      row.classList.add('bump');
    }

    list.append(row);
  });

  /* FLIP: play the difference. */
  list.querySelectorAll('.row').forEach(row => {
    const old = before.get(row.dataset.name);
    if (old === undefined) return;
    const delta = old - row.getBoundingClientRect().top;
    if (!delta) return;
    row.style.transform = `translateY(${delta}px)`;
    row.style.transition = 'none';
    requestAnimationFrame(() => {
      row.style.transition = '';
      row.style.transform = '';
    });
  });

  data.standings.forEach(r => lastTotals.set(r.name, r.total));
}

function countUp(node, from, to) {
  if (from === to) { node.textContent = to; return; }
  const start = performance.now(), dur = 900;
  const step = now => {
    const t = Math.min(1, (now - start) / dur);
    const eased = 1 - Math.pow(1 - t, 3);
    node.textContent = Math.round(from + (to - from) * eased);
    if (t < 1) requestAnimationFrame(step);
  };
  requestAnimationFrame(step);
}

function renderTeams(data) {
  const us = $('#teams-us'), intl = $('#teams-intl');
  us.innerHTML = ''; intl.innerHTML = '';
  const order = { world_champion: 0, side_champion: 1, winners: 2, elimination: 3, eliminated: 4 };
  [...data.teams]
    .sort((a, b) => (order[a.state] - order[b.state]) || (b.points - a.points) ||
                    a.team.localeCompare(b.team))
    .forEach(t => {
      const card = el('div', 'team ' + t.state);
      card.append(el('div', 'team-name', t.display || shown(t.team)));
      card.append(el('div', 'team-pts', t.points));
      card.append(el('div', 'team-region', t.team));
      card.append(el('div', 'team-status', t.label));
      const picked = el('div', 'team-picked');
      if (t.picked_by) {
        picked.innerHTML = `picked by <b>${t.picked_by}</b>` +
          (t.picked_at_one ? ` · <b>${t.picked_at_one}</b> at #1` : '');
      } else {
        picked.innerHTML = '<span>picked by nobody</span>';
      }
      card.append(picked);
      (t.side === 'US' ? us : intl).append(card);
    });
}

/* What this particular screen reports about itself. The office TV is a
   BrightSign and behaves differently from any browser here, so rather than
   guess, ?debug=1 puts the numbers on the screen to be read off. */
function renderDebug(data) {
  if (!DEBUG) return;
  let box = $('#debug-box');
  if (!box) {
    box = el('div');
    box.id = 'debug-box';
    document.body.appendChild(box);
  }
  const rows = document.querySelectorAll('#standings .row');
  const pitch = rows.length > 1
    ? Math.round(rows[1].getBoundingClientRect().top -
                 rows[0].getBoundingClientRect().top)
    : 0;
  const supports = (prop, val) => {
    try { return window.CSS && CSS.supports && CSS.supports(prop, val); }
    catch (e) { return 'n/a'; }
  };
  const avail = Math.round($('#ticker').getBoundingClientRect().top
                           - $('#standings').getBoundingClientRect().top);
  box.innerHTML = [
    'viewport ' + window.innerWidth + ' x ' + window.innerHeight +
      '  dpr ' + (window.devicePixelRatio || 1),
    'entries ' + data.standings.length + '   rows/page ' + pageSize +
      '   rendered ' + rows.length + '   views ' + VIEWS.length +
      '   showing ' + (viewIndex + 1),
    'space above ticker ' + avail + 'px   row pitch ' + pitch + 'px',
    'resumed at view ' + resumeFrom + '   rotating every ' +
      Math.round(rotateMs() / 1000) + 's' + (paused ? ' (paused)' : ''),
    'flex gap ' + supports('row-gap', '1px') +
      '   clip-path ' + supports('clip-path', 'polygon(0 0, 1px 0, 0 1px)') +
      '   css vars ' + supports('--x', '1px'),
    navigator.userAgent
  ].join('<br>');
}

function renderTicker(data) {
  const latest = data.recent[0];
  $('#tick-latest').innerHTML = latest
    ? `<span class="win">${latest.winner_display || shown(latest.winner)}</span>` +
      ` def. ${latest.loser_display || shown(latest.loser)}` +
      ` <span class="dim">&mdash; ${latest.label} (G${latest.game})</span>`
    : '<span class="dim">No games played yet</span>';

  const next = data.upcoming[0];
  $('#tick-next').innerHTML = next
    ? `${next.a_display || shown(next.a)} <span class="dim">vs</span> ` +
      `${next.b_display || shown(next.b)}` +
      ` <span class="dim">&mdash; ${next.label}, ` +
      `${fmtWhen(next.date, next.time, data.timezone || 'PT')}</span>`
    : '<span class="dim">Tournament complete</span>';
}

function fmtDate(iso) {
  const d = new Date(iso + 'T12:00:00');
  return d.toLocaleDateString(undefined, { weekday: 'short', month: 'short', day: 'numeric' });
}

/* Today needs no date on it, and the space buys the full matchup. */
function fmtWhen(iso, time, tz) {
  const today = new Date();
  const pad = n => String(n).padStart(2, '0');
  const key = `${today.getFullYear()}-${pad(today.getMonth() + 1)}-${pad(today.getDate())}`;
  return (iso === key ? '' : fmtDate(iso) + ' ') + time + ' ' + tz;
}

/* ------------------------------------------------------------- rotation */
function showView(i) {
  viewIndex = (i + VIEWS.length) % VIEWS.length;
  if (!PINNED) {
    try { localStorage.setItem(VIEW_KEY, viewIndex); } catch (e) {}
  }
  const view = VIEWS[viewIndex];
  if (isNarrow()) {
    // On a phone nothing rotates: both sections stack and the page scrolls,
    // so a screen never changes out from under whoever is reading it.
    $('#view-standings').classList.remove('hidden');
    $('#view-teams').classList.remove('hidden');
    $('#view-dots').innerHTML = '';
    return;
  }
  $('#view-standings').classList.toggle('hidden', view.kind !== 'standings');
  $('#view-teams').classList.toggle('hidden', view.kind !== 'teams');
  const dots = $('#view-dots');
  dots.innerHTML = '';
  VIEWS.forEach((_, idx) =>
    dots.append(el('span', 'vdot' + (idx === viewIndex ? ' on' : ''))));
}

/* Paging between standings pages re-renders that page's rows. */
function goto(i) {
  showView(i);
  if (currentData) {
    renderStandings(currentData);
  }
}
let currentData = null;

function restartRotation() {
  clearInterval(rotateTimer);
  if (paused || isNarrow() || VIEWS.length < 2) return;
  rotateTimer = setInterval(() => goto(viewIndex + 1), rotateMs());
}

document.addEventListener('keydown', e => {
  if (e.code === 'Space') {
    e.preventDefault();
    paused = !paused;
    restartRotation();
  } else if (e.code === 'ArrowRight') {
    goto(viewIndex + 1); restartRotation();
  } else if (e.code === 'ArrowLeft') {
    goto(viewIndex - 1); restartRotation();
  } else if (e.key === '[') {
    nudgeSafe(0.5);           // crop more: pull the picture in
  } else if (e.key === ']') {
    nudgeSafe(-0.5);          // crop less: push the picture out
  } else if (e.key === '0') {
    safePercent = 3; nudgeSafe(0);
  }
});

applySafe(false);

